<#
.SYNOPSIS
  Terraform outputs (40-aks) -> gitops/envs/<env>/platform.values.yaml

.DESCRIPTION
  This is the "contract" between infrastructure (Terraform) and delivery (GitOps):
  Terraform creates the ACR, identity, Key Vault and SQL server with random
  suffixes; this script writes those names into the Helm values Argo CD reads.
  Commit the result through a PR — Git stays the source of truth.
#>
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$Root = Split-Path $PSScriptRoot -Parent

& (Join-Path $PSScriptRoot 'azp.ps1') init 40-aks | Out-Null
$o = (& terraform "-chdir=$(Join-Path $Root 'infra/terraform/40-aks')" output -json) | ConvertFrom-Json
if (-not $o.acr_login_server) { throw '40-aks has no outputs. Apply it first.' }

foreach ($env in 'dev', 'prod') {
  $file = Join-Path $Root "gitops/envs/$env/platform.values.yaml"
  @"
# GENERATED by scripts/render-gitops-values.ps1 from Terraform outputs
# (40-aks). Commit the regenerated file whenever the infra is recreated.
image:
  registry: $($o.acr_login_server.value)
workloadIdentity:
  clientId: $($o.portal_api_client_id.value)
  tenantId: $($o.tenant_id.value)
sql:
  server: $($o.sql_server_fqdn.value)
keyVault:
  name: $($o.key_vault_name.value)
"@ | Set-Content $file -Encoding utf8
  Write-Host "wrote $file"
}

Write-Host "`nNext: git checkout -b chore/platform-values && git add gitops/envs && git commit -m 'chore: platform values' && git push (open a PR)"
